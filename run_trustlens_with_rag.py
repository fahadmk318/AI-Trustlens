#!/usr/bin/env python3
"""AI TrustLens - integrated question -> claims -> evidence entry point.

This runner coexists with the untouched baseline app.py; it reuses app.py's
query_model through a safe adapter whenever an automatic answer is requested,
and never changes the baseline model, Ollama configuration, or GPU settings.

Modes
-----
1. Automatic (requires a running Ollama daemon with the baseline model):
       python run_trustlens_with_rag.py --question "What causes fever?"
   The baseline answer is generated by the teammate's untouched app.py
   (qwen3:8b), then extracted into claims by the untouched claimextractor.py,
   then each claim is sent to the RAG evidence API.

2. Manual answer mode (no baseline model call; the claim extractor still runs):
       python run_trustlens_with_rag.py --answer "Fever is a temporary rise
       in body temperature."
       python run_trustlens_with_rag.py --answer-file path/to/answer.txt

   Limitation: the answer text is supplied by the user rather than generated
   by the baseline QA model; this mode is meant for testing the
   claims->evidence stage without Ollama.

3. Health check only:
       python run_trustlens_with_rag.py --health

The RAG service must be running separately (see rag_integration docs):
       cd <rag repo>; .venv\\Scripts\\python.exe -m uvicorn app.main:app --host 127.0.0.1 --port 8000

The RAG API base URL defaults to http://127.0.0.1:8000 and can be overridden
with the environment variable RAG_API_BASE_URL (also accepted via --rag-url).

Output is a JSON document with per-claim evidence. verification_status stays
"Not Evaluated": retrieval is evidence, not verification.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Dict, Optional

from rag_integration import (
    RAGClient,
    RAGConnectionError,
    RAGHTTPError,
    RAGInvalidResponseError,
    RAGTimeoutError,
    TrustLensRAGPipeline,
    get_config,
)


def _parse_args(argv: Optional[list] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run the AI TrustLens integrated QA -> claims -> evidence pipeline")
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--question", help="medical question; the baseline answer is generated via app.py's query_model (requires Ollama)")
    source.add_argument("--answer", help="provide the answer text directly (manual mode; the claim extractor still runs)")
    source.add_argument("--answer-file", dest="answer_file", help="read the answer text from a UTF-8 file (manual mode)")
    source.add_argument("--health", action="store_true", help="only check the RAG service health and exit")
    parser.add_argument("--top-k", dest="top_k", type=int, default=None, help="evidence items per claim (default from RAG_API_TOP_K, else 5)")
    parser.add_argument("--retrieval-mode", dest="retrieval_mode", choices=["vector", "bm25", "graph", "hybrid"], default=None, help="retrieval strategy (default hybrid)")
    parser.add_argument("--domain", default=None, help="metadata filter for the corpus, e.g. 'Medical'\"")
    parser.add_argument("--rag-url", dest="rag_url", default=None, help="RAG API base URL (default: RAG_API_BASE_URL env or http://127.0.0.1:8000)")
    parser.add_argument("--refine", action="store_true", help="enable the extractor's optional LLM refinement stage (extra Ollama calls)")
    parser.add_argument("--out", default=None, help="also write the JSON result to this file")
    return parser.parse_args(argv)


def _load_answer(args: argparse.Namespace) -> str:
    if args.answer is not None and args.answer.strip():
        return args.answer
    if args.answer_file:
        try:
            with open(args.answer_file, "r", encoding="utf-8") as handle:
                text = handle.read()
        except OSError as exc:
            print(json.dumps({"error": f"could not read answer file: {exc}"}))
            raise SystemExit(2)
        if text.strip():
            return text
    print(json.dumps({"error": "no answer text was supplied in manual mode"}))
    raise SystemExit(2)


def _write_output(path: str, payload: Dict[str, Any]) -> None:
    try:
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2, ensure_ascii=False)
    except OSError as exc:
        print(f"[warn] could not write output file: {exc}", file=sys.stderr)


def main(argv: Optional[list] = None) -> int:
    args = _parse_args(argv)

    # --rag-url takes precedence over RAG_API_BASE_URL; Both feed the same
    # config path.
    if args.rag_url:
        os.environ["RAG_API_BASE_URL"] = args.rag_url
    config = get_config()

    pipeline = TrustLensRAGPipeline(
        config=config,
        claim_processor=None,
        answer_provider=None,  # unused: this runner wires modes itself
    )
    pipeline.claim_processor.refine = bool(args.refine) or pipeline.claim_processor.refine

    try:
        if args.health:
            client = RAGClient(config)
            health = client.health()
            print(json.dumps(health, indent=2, ensure_ascii=False))
            return 0

        if args.question:
            result = pipeline.process_question(
                args.question,
                top_k=args.top_k,
                retrieval_mode=args.retrieval_mode,
                domain=args.domain,
            )
        else:
            answer = _load_answer(args)
            result = pipeline.process_answer(
                args.question or "",
                answer,
                top_k=args.top_k,
                retrieval_mode=args.retrieval_mode,
                domain=args.domain,
            )
    except RAGHTTPError as exc:
        print(json.dumps({
            "error": f"RAG API failure: {exc}",
            "status_code": exc.status_code,
            "detail": exc.detail,
        }))
        return 3
    except RAGConnectionError as exc:
        print(json.dumps({
            "error": f"cannot reach the RAG service: {exc}",
            "hint": "Start the RAG API in its own repo, e.g. "
                    "python -m uvicorn app.main:app --host 127.0.0.1 --port 8000",
        }))
        return 3
    except (RAGTimeoutError, RAGInvalidResponseError, RAGClientError) as exc:
        print(json.dumps({"error": f"RAG API failure: {exc}"}))
        return 3
    except RuntimeError as exc:
        print(json.dumps({"error": f"pipeline failure: {exc}"}))
        return 4
    finally:
        pipeline.close()

    print(json.dumps(result, indent=2, ensure_ascii=False))
    if args.out:
        _write_output(args.out, result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
