#!/usr/bin/env python3
"""
AI TrustLens - Stage 1: Baseline Medical Question-Answering Application
-----------------------------------------------------------------------
Final-Year B.Tech Project - Stage 1 Baseline System.

This script implements a local, terminal-based medical QA tool connecting
directly to a locally hosted Qwen3-8B model via the Ollama Python SDK.

Key Configuration:
- Model: qwen3:8b (hosted locally via Ollama)
- Temperature: 0 (deterministic, greedy sampling)
- Think: False (suppresses chain-of-thought tokens if supported by model/Ollama)
- num_predict: 200 (caps generated answer length to ~200 tokens)

Note: This is Stage 1 (Baseline). No RAG, NER, Knowledge Graphs, or
hallucination verification components are included in this stage.
Answers are raw baseline outputs and are NOT medically verified.
"""

import sys
import os
import ollama
from ollama import ResponseError, RequestError

# Configuration Constants
DEFAULT_MODEL = "qwen3:8b"
TEMPERATURE = 0.0
MAX_TOKENS = 200
THINK_SETTING = False

# ANSI Color codes for clean terminal output (disabled if not supported)
USE_COLOR = sys.stdout.isatty()
CYAN = "\033[96m" if USE_COLOR else ""
GREEN = "\033[92m" if USE_COLOR else ""
YELLOW = "\033[93m" if USE_COLOR else ""
RED = "\033[91m" if USE_COLOR else ""
BOLD = "\033[1m" if USE_COLOR else ""
DIM = "\033[2m" if USE_COLOR else ""
RESET = "\033[0m" if USE_COLOR else ""

DISCLAIMER = (
    "DISCLAIMER: This system is a research prototype (AI TrustLens Stage 1 Baseline).\n"
    "Outputs generated by the local language model are unverified, may contain errors\n"
    "or hallucinations, and MUST NOT be used for real medical decision-making or diagnosis."
)


def print_banner() -> None:
    """Print the application header, operational parameters, and safety disclaimer."""
    print("=" * 72)
    print(f"{BOLD}{CYAN}      AI TrustLens - Stage 1: Baseline Medical QA System{RESET}")
    print("=" * 72)
    print(f"{DIM}Model: {DEFAULT_MODEL} | Temp: {TEMPERATURE} | Max Tokens: {MAX_TOKENS} | Think: {THINK_SETTING}{RESET}")
    print(f"{YELLOW}{DISCLAIMER}{RESET}")
    print("=" * 72)
    print("Type your medical question below, or type 'exit' or 'quit' to close.\n")


def query_model(question: str, model_name: str = DEFAULT_MODEL) -> str | None:
    """
    Send the user question to the local Ollama instance and return the response.

    Args:
        question: The user-supplied medical question.
        model_name: The target local model identifier (default: qwen3:8b).

    Returns:
        The text response generated by the model, or None if an error occurred.
    """
    messages = [
        {
            "role": "user",
            "content": question,
        }
    ]

    # Model inference options:
    # - temperature: 0 produces greedy, reproducible outputs
    # - num_predict: limits the generated completion tokens to ~200
    options = {
        "temperature": TEMPERATURE,
        "num_predict": MAX_TOKENS,
    }

    try:
        response = ollama.chat(
            model=model_name,
            messages=messages,
            think=THINK_SETTING,
            options=options,
        )

        # Extract model text content from chat response
        if response and hasattr(response, "message") and response.message:
            return response.message.content
        return None

    except ResponseError as e:
        # Handles errors returned by Ollama server (e.g., 404 model not found)
        if e.status_code == 404:
            print(f"{RED}[Error] Model '{model_name}' was not found in your local Ollama library.{RESET}")
            print(f"{YELLOW}Hint: Verify existing models using `ollama list`.{RESET}")
        else:
            print(f"{RED}[Ollama Server Error] {e.error} (Status code: {e.status_code}){RESET}")
        return None

    except RequestError as e:
        # Handles network / connection errors connecting to the local Ollama daemon
        print(f"{RED}[Connection Error] Unable to connect to local Ollama service.{RESET}")
        print(f"{YELLOW}Details: {e}{RESET}")
        print(f"{YELLOW}Hint: Ensure Ollama is running (`ollama serve` or `systemctl status ollama`).{RESET}")
        return None

    except ConnectionError as e:
        print(f"{RED}[Network Error] Could not establish connection to local Ollama daemon.{RESET}")
        print(f"{YELLOW}Details: {e}{RESET}")
        print(f"{YELLOW}Hint: Ensure Ollama is running (`ollama serve` or `systemctl status ollama`).{RESET}")
        return None

    except Exception as e:
        # Generic fallback for any unexpected runtime errors
        print(f"{RED}[Unexpected Error] An error occurred while generating the answer: {e}{RESET}")
        return None


def run_interactive_loop() -> None:
    """Run the main terminal interaction loop, accepting questions until the user exits."""
    print_banner()

    while True:
        try:
            # Prompt the user for input
            user_input = input(f"{BOLD}{CYAN}Question>{RESET} ").strip()

        except (KeyboardInterrupt, EOFError):
            # Gracefully handle Ctrl+C or Ctrl+D
            print(f"\n\n{YELLOW}Session terminated by user. Exiting AI TrustLens.{RESET}")
            break

        # Check for exit commands
        if user_input.lower() in {"exit", "quit", "q"}:
            print(f"\n{GREEN}Exiting AI TrustLens. Goodbye!{RESET}")
            break

        # Handle empty or whitespace-only input gracefully
        if not user_input:
            print(f"{YELLOW}[Notice] Input cannot be empty. Please enter a valid medical question.{RESET}\n")
            continue

        print(f"{DIM}Generating baseline answer from {DEFAULT_MODEL}...{RESET}")

        # Query the local model
        answer = query_model(user_input, model_name=DEFAULT_MODEL)

        if answer:
            print(f"\n{BOLD}{GREEN}[Answer (Baseline - Unverified)]{RESET}")
            print("-" * 72)
            print(answer.strip())
            print("-" * 72)
            print(f"{DIM}(Token limit: ~{MAX_TOKENS} tokens | Model: {DEFAULT_MODEL} | Unverified Baseline){RESET}\n")
        else:
            print(f"{RED}[Notice] Could not generate an answer for this query.{RESET}\n")


if __name__ == "__main__":
    run_interactive_loop()
